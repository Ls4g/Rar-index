import assert from "node:assert/strict";
import { catalogueWindow } from "../lib/catalogueWindow.ts";
const rows = Array.from({ length: 123 }, (_, i) => ({ id: `00000000-0000-0000-0000-${String(i).padStart(12,"0")}` }));
const read = (from,to) => Promise.resolve({ data: rows.slice(from,to+1), count: rows.length, error: null });
const focus = (id) => Promise.resolve({ data: rows.find(r=>r.id===id) ?? null, error: null });
const visited = [];
for (let page=1;page<=3;page++) visited.push(...(await catalogueWindow(String(page),undefined,read,focus)).records);
assert.deepEqual(visited, rows);
assert.equal((await catalogueWindow("999",undefined,read,focus)).page,3);
assert.equal((await catalogueWindow("bad",undefined,read,focus)).page,1);
const linked = await catalogueWindow("1",rows[120].id,read,focus);
assert.equal(linked.records[0].id,rows[120].id);
assert.equal(linked.records.length,51);
assert.equal(linked.pageRows,50);
assert.equal((await catalogueWindow("1",rows[0].id,read,focus)).records.length,50);
assert.equal((await catalogueWindow("1","bad",read,focus)).focusedMissing,true);
await assert.rejects(catalogueWindow("1",undefined,async()=>({data:null,count:null,error:{message:"offline"}}),focus), /could not be loaded/);
await assert.rejects(catalogueWindow("1",rows[120].id,read,async()=>({data:null,error:{message:"offline"}})), /could not be loaded/);
console.log("Catalogue pagination: complete traversal, focused records, deduplication, bad input and failure states passed.");
